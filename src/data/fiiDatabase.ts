export interface SearchFiiResult {
  fund: FiiData;
  isAliasMatch: boolean;
  searchedTerm: string;
  matchedAlias?: string;
  aliasMessage?: string;
}

/**
 * Busca fundos por ticker atual ou por tickers antigos/incorporados.
 */
export function searchFii(query: string): SearchFiiResult | null {
  const cleanQuery = query.trim().toUpperCase();
  if (!cleanQuery) return null;

  // 1. Busca exata por ticker atual
  const exactMatch = FII_DATABASE.find(f => f.ticker === cleanQuery);
  if (exactMatch) {
    return {
      fund: exactMatch,
      isAliasMatch: false,
      searchedTerm: cleanQuery,
    };
  }

  // 2. Busca exata em tickers antigos (aliases)
  const aliasMatch = FII_DATABASE.find(f =>
    f.previousTickers.some(alias => alias === cleanQuery)
  );
  if (aliasMatch) {
    return {
      fund: aliasMatch,
      isAliasMatch: true,
      searchedTerm: cleanQuery,
      matchedAlias: cleanQuery,
      aliasMessage: `Atenção: O ticker ${cleanQuery} migrou para ${aliasMatch.ticker} (${aliasMatch.name}) na B3. Os dados foram carregados automaticamente com base no código atual oficial.`,
    };
  }

  // 3. Busca parcial por ticker ou nome
  const partialMatch = FII_DATABASE.find(
    f =>
      f.ticker.includes(cleanQuery) ||
      f.previousTickers.some(alias => alias.includes(cleanQuery)) ||
      f.name.toUpperCase().includes(cleanQuery)
  );

  if (partialMatch) {
    const isOld = partialMatch.previousTickers.some(alias => alias.includes(cleanQuery));
    return {
      fund: partialMatch,
      isAliasMatch: isOld,
      searchedTerm: cleanQuery,
      matchedAlias: isOld ? cleanQuery : undefined,
      aliasMessage: isOld
        ? `Atenção: Você buscou por ${cleanQuery}, antigo código do fundo imobiliário que hoje é negociado como ${partialMatch.ticker} (${partialMatch.name}).`
        : undefined,
    };
  }

  return null;
}

/**
 * Formatação de Moeda Brasileira (R$ 0,00)
 */
export function formatCurrency(value: number): string {
  if (isNaN(value) || !isFinite(value)) return 'R$ 0,00';
  const formatted = Math.abs(value).toLocaleString('pt-BR', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
  return `${value < 0 ? '-' : ''}R$ ${formatted}`;
}

/**
 * Formatação de Porcentagem (%)
 */
export function formatPercent(value: number, decimals: number = 2): string {
  if (isNaN(value) || !isFinite(value)) return '0,00%';
  return `${value.toLocaleString('pt-BR', {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  })}%`;
}

/**
 * Formatação de Número Decimal (ex: P/VP 0,95)
 */
export function formatDecimal(value: number, decimals: number = 2): string {
  if (isNaN(value) || !isFinite(value)) return '0,00';
  return value.toLocaleString('pt-BR', {
    minimumFractionDigits: decimals,
    maximumFractionDigits: decimals,
  });
}

/**
 * Formatação de Número Inteiro com separador de milhar (ex: 455.000)
 */
export function formatInteger(value: number): string {
  if (isNaN(value) || !isFinite(value)) return '0';
  return Math.round(value).toLocaleString('pt-BR');
}

/**
 * Formatação compacta de Cotistas (ex: 455 mil)
 */
export function formatCotistas(count: number): string {
  if (count >= 1000) {
    const mil = Math.round(count / 1000);
    return `${mil} mil`;
  }
  return formatInteger(count);
}

/**
 * Formatação de Patrimônio em Bilhões (ex: R$ 6,35 bi)
 */
export function formatBillion(value: number): string {
  if (isNaN(value) || !isFinite(value)) return 'R$ 0,00 bi';
  return `R$ ${value.toLocaleString('pt-BR', { minimumFractionDigits: 2, maximumFractionDigits: 2 })} bi`;
}

/**
 * Converte valor de input com máscara monetária (ex: "R$ 97,07" ou "9707") para número decimal (ex: 97.07)
 */
export function parseCurrencyInput(value: string): number {
  if (!value) return 0;
  const digits = value.replace(/\D/g, '');
  if (!digits) return 0;
  return Number(digits) / 100;
}

/**
 * Formata um valor numérico ou string com a máscara monetária brasileira "R$ 0,00"
 */
export function formatCurrencyMask(value: number | string): string {
  let num: number;
  if (typeof value === 'number') {
    num = value;
  } else {
    num = parseCurrencyInput(value);
  }
  if (num === 0) return '';
  return formatCurrency(num);
}
